import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const core=await readFile(resolve(root,'supabase/functions/_shared/core.ts'),'utf8');
const check=process.argv.includes('--check');
for(const name of ['ai-narasi','ai-chat']){
 const folder=resolve(root,'supabase/functions',name);
 const handler=await readFile(resolve(folder,'handler.ts'),'utf8');
 const sharedImport=/^import\s*\{[^}]+\}\s*from\s*['"]\.\.\/_shared\/core\.ts['"];?\s*\r?\n/m;
 if(!sharedImport.test(handler))throw Error(`Import helper tidak ditemukan pada ${name}/handler.ts. Persiapan dihentikan agar kode tidak berubah tanpa pemeriksaan.`);
 const entry=`// GENERATED by scripts/prepare-edge-functions.mjs.\n// Edit _shared/core.ts and ${name}/handler.ts, then run npm run prepare:edge.\n// Self-contained entrypoint avoids missing local assets with CLI API bundling.\n${core}\n${handler.replace(sharedImport,'')}`;
 if(/from\s*['"]\.\.?\//.test(entry))throw Error('Entrypoint masih memiliki import lokal.');
 const path=resolve(folder,'index.ts');
 if(check){if(await readFile(path,'utf8')!==entry)throw Error(`${name}/index.ts belum diperbarui. Jalankan npm run prepare:edge.`)}
 else await writeFile(path,entry,'utf8');
 console.log(`OK: ${name}/index.ts ${check?'sesuai sumber':'siap deploy, tanpa import lokal'}`);
}
